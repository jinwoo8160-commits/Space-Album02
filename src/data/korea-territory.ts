/** 대마도·이키 등: 폴리곤이 헐거워도 이 박스는 무조건 제외. */
export function isForeignIsland(lng: number, lat: number) {
  const tsushima = lat >= 34.02 && lat <= 34.82 && lng >= 129.12 && lng <= 129.55;
  const iki = lat >= 33.68 && lat <= 33.9 && lng >= 129.58 && lng <= 129.82;
  const okinoshima = lat >= 34.2 && lat <= 34.28 && lng >= 130.05 && lng <= 130.15;
  return tsushima || iki || okinoshima;
}

export function isInKoreaTerritory(lng: number, lat: number) {
  if (isForeignIsland(lng, lat)) return false;
  const point: [number, number] = [lng, lat];
  return KOREA_RINGS.some((ring) => pointInRing(point, ring));
}

function pointInRing(point: [number, number], ring: Ring): boolean {
  const x = point[0];
  const y = point[1];
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i, i += 1) {
    const xi = ring[i]![0]!;
    const yi = ring[i]![1]!;
    const xj = ring[j]![0]!;
    const yj = ring[j]![1]!;
    const intersect = yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi + Number.EPSILON) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

